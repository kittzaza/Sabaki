// Thai translation of Sabaki's interface.
//
// Keys are the English strings with the menu accelerator '&' already stripped
// -- src/i18n.js `getKey` removes it before lookup, so a key written as
// '&Save' would never match and would silently fall back to English.
//
// Strings taking parameters must be functions. Written as a plain string, the
// `${...}` would be shown to the user verbatim.
//
// Go vocabulary that has no settled Thai word (ko, hane, atari, komi …) is
// transliterated with a short gloss in brackets: a beginner can read it, and a
// player who already knows the term can still match it against other Go
// material, which a pure translation would prevent.

